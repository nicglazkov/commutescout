// Final proposal, Home figure: the sorting bench, generic, with a dedupe station.
// Generator for components/figures/feed-bench.tsx (anatomy kit, vendored in ../kit).
//   node site/components/figures/_build/bench/bench.mjs   -> writes ../../feed-bench.art.ts
// Geometry lives in pipe.mjs; this file expands the hopper prototypes for the no-JS picture,
// shortens class names, and writes the drawing, its camera basis and the station marks as a TS module.
import { writeFileSync } from "node:fs";
import { PIPE, GEOM, VIEW, MARKS } from "./pipe.mjs";

let svg = PIPE.svg;
const protos = {};
svg.replace(/<g data-proto="([^"]+)">([\s\S]*?)<\/g><!--\/proto-->/g, (m, n, inner) => { protos[n] = inner; return m; });
// hoppers and their lips are drawn in place (no-JS frame); cards stay as one prototype the script clones
svg = svg.replace(/<g data-use="(p-hop|p-lip)"([^>]*)><\/g>/g, (m, n, rest) => `<g${rest}>${protos[n]}</g>`);
svg = svg.replace(/<g data-proto="(p-hop|p-lip)">[\s\S]*?<\/g><!--\/proto-->/g, "");

// a solid's top and side faces cover its silhouette, so its paper fill is redundant
svg = svg.replace(/(<g class="iso-solid"[^>]*>)<path class="iso-fill" d="[^"]*"\/>(?=<path class="iso-shade|<path class="iso-top)/g, "$1");
svg = svg.replace(/<path class="iso-line iso-bevel"[^>]*\/>/g, "");
const TONE = { lo: "lo", mid: "mi", hi: "hi", faint: "fa", lit: "li" };
svg = svg
  .replace(/ data-seamless=""/g, "")
  .replace(/ data-free="[^"]*"/g, "")
  .replace(/class="iso-solid"/g, 'class="o"')
  .replace(/class="iso-solid ([^"]*)"/g, 'class="o $1"')
  .replace(/class="iso-fill"/g, 'class="f"')
  .replace(/class="iso-top"/g, 'class="t"')
  .replace(/class="iso-halo"/g, 'class="h"')
  .replace(/class="iso-shade" data-shade="(\d)"/g, 'class="s$1"')
  .replace(/class="iso-line(?: iso-crease| iso-edge)?( [^"]*)?" data-tone="(\w+)"/g, (m, extra, t) => `class="l ${TONE[t]}${extra || ""}"`)
  .replace(/class="iso-dots" data-tone="(\w+)"/g, (m, t) => `class="d ${TONE[t]}"`)
  .replace(/class="iso-wire-end"/g, 'class="we"')
  .replace(/class="iso-svg csfig-svg"/g, 'class="csf-svg iso bench-svg"')
  .replace(/<circle cx="([\d.-]+)" cy="([\d.-]+)" r="([\d.]+)"\/>/g, (m, x, y, r) => `<circle cx="${(+x).toFixed(1)}" cy="${(+y).toFixed(1)}" r="${(+r).toFixed(2)}"/>`)
  .replace(/<g class="cs-hopper" data-feed="(\d)"[^>]*>/g, '<g class="cs-hopper" data-feed="$1">') // controls live in HTML buttons under the drawing
  .replace(/style="filter:blur\(\d+px\)" /g, "");

// budget: soft shadows only under the plate and the big stations (blur is costly to paint and to ship)
let halos = 0;
svg = svg.replace(/<path class="h" d="[^"]*"\/>/g, (m) => (halos++ < 6 ? m : ""));
// strip the outer <svg> wrapper: the React component writes its own with the accessible name
const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "").replace(/<title>[\s\S]*?<\/title><desc>[\s\S]*?<\/desc>/, "");
// Ship size (target <= 90 KB raw), lossless: the markup is parsed by the HTML parser
// (static HTML and innerHTML), so single-token attribute values need no quotes and the
// rest take single quotes, which JSON.stringify does not have to escape.
const lean = inner
  .replace(/="([A-Za-z0-9_-]+)"/g, "=$1")
  .replace(/="([^"']*)"/g, "='$1'");
const ts = `// Generated by components/figures/_build/bench/bench.mjs (anatomy kit). Do not edit by hand.
export const BENCH_VIEW = ${JSON.stringify(VIEW)} as const;
export const BENCH_GEOM = ${JSON.stringify(GEOM)};
export const BENCH_MARKS: Record<string, [number, number]> = ${JSON.stringify(MARKS)};
export const BENCH_SVG = ${JSON.stringify(lean)};
`;
writeFileSync(new URL("../../feed-bench.art.ts", import.meta.url), ts);
console.log("feed-bench.art.ts", ts.length, "bytes; card proto", protos["p-card"].length);
