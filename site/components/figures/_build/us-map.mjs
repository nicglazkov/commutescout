// Build-time generator for us-coverage-map.tsx: precomputes state outlines so no d3 ships to the client.
// Source: us-atlas@3.0.1 states-albers-10m.json (already projected with geoAlbersUsa into 975 x 610).
// Run: mkdir /tmp/csgeo && cd /tmp/csgeo && npm i us-atlas@3.0.1 topojson-client@3.1.0 topojson-simplify@3.0.3 d3-geo@3.1.1
//      NODE_PATH=/tmp/csgeo/node_modules node site/components/figures/_build/us-map.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(process.env.NODE_PATH + "/");
const topo = require("us-atlas/states-albers-10m.json");
const { feature, mesh } = require("topojson-client");
const { presimplify, simplify } = require("topojson-simplify");
const { geoPath } = require("d3-geo");

const t = simplify(presimplify(topo), +(process.env.W || 2));
const fc = feature(t, t.objects.states);
// relative path data at 0.5 px precision: every ring is closed, so nothing drifts
const q = (v) => Math.round(v * 2) / 2;
const f = (v) => { const s = String(v); return s.startsWith("0.") ? s.slice(1) : s.startsWith("-0.") ? "-" + s.slice(2) : s; };
const round = (d) => d.split(/(?=M)/).map((ring) => {
  const pts = (ring.match(/-?\d+(?:\.\d+)?/g) || []).map(Number);
  let out = "", px = 0, py = 0, first = true, n = 0;
  for (let i = 0; i < pts.length; i += 2) {
    const x = q(pts[i]), y = q(pts[i + 1]);
    if (!first && x === px && y === py) continue;
    const dx = f(q(x - px)), dy = f(q(y - py));
    out += (first ? "M" + x + " " + y : (n === 1 ? "l" : (dx[0] === "-" ? "" : " ")) + dx + (dy[0] === "-" ? "" : " ") + dy);
    px = x; py = y; first = false; n++;
  }
  return out + "z";
}).join("");
const path = geoPath();
const states = fc.features
  .map((f) => ({ id: f.id, name: f.properties.name, d: round(path(f)), c: path.centroid(f).map((v) => Math.round(v)) }))
  .sort((a, b) => a.name.localeCompare(b.name));
const nation = round(path(mesh(t, t.objects.nation)));
const out = `// Generated by components/figures/_build/us-map.mjs from us-atlas@3.0.1 states-albers-10m
// (geoAlbersUsa, 975 x 610 viewBox, simplified). Do not edit by hand.
export type StateShape = { id: string; name: string; d: string; c: [number, number] };
export const US_VIEWBOX = "0 0 975 610";
export const US_NATION = ${JSON.stringify(nation)};
export const US_STATES: StateShape[] = ${JSON.stringify(states)};
`;
writeFileSync(new URL("../us-map.geo.ts", import.meta.url), out);
console.log("us-map.geo.ts", out.length, "bytes", states.length, "states");
